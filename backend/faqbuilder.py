def _clean_list(xs) -> list[str]:
    out = []
    for x in xs or []:
        x = str(x).strip()
        if x and x not in out:
            out.append(x)
    return out


def build(facts: list[dict], augment: bool = True, include_defaults: bool = True) -> dict:
    """คืน {"train":[{instruction,input,output}], "eval":[{text,category,expect,must_not,red_flag,pinned}], "stats":{...}}
    ข้อเท็จจริงที่ไม่มีคำตอบหรือไม่มีคำถามจะถูกข้าม (นับใน skipped)"""
    train: list[dict] = []
    seen: set[str] = set()
    ev: list[dict] = []
    skipped = 0
    for f in facts:
        topic = str(f.get("topic", "")).strip() or "ทั่วไป"
        answer = str(f.get("answer", "")).strip()
        qs = _clean_list(f.get("questions"))
        kws = _clean_list(f.get("keywords"))
        must_not = _clean_list(f.get("must_not"))
        if not answer or not qs:
            skipped += 1
            continue
        hold = None
        if len(qs) >= 3 and (kws or must_not):  # เหลือคำถามเทรนอย่างน้อย 2 แบบ ถึงจะกันข้อสอบไว้ได้
            hold = qs[-1]
            qs = qs[:-1]
        for q in qs:
            for p in (PREFIXES if augment else PREFIXES[:1]):
                text = p + q
                if text in seen:
                    continue
                seen.add(text)
                train.append({"instruction": text, "input": "", "output": answer})
        if hold and hold not in seen:
            ev.append({"text": hold, "category": topic, "expect": kws, "must_not": must_not,
                       "red_flag": bool(f.get("red_flag")), "pinned": True})
    if include_defaults:
        for q, a in DEFAULT_EXAMPLES:
            if q not in seen:
                seen.add(q)
                train.append({"instruction": q, "input": "", "output": a})
    return {"train": train, "eval": ev, "stats": {"train": len(train), "eval": len(ev), "skipped": skipped}}
